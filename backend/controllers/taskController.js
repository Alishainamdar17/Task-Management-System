const createTask = async (req, res) => {
  try {
    let {
      title,
      description,
      status,
      priority,
      project,
      dueDate,
      assignees = [],
      attachments = [],
      subtasks = [],
      dependencies = [],
      todoChecklist = []
    } = req.body;

    if (!title) return res.status(400).json({ message: 'Title is required' });

    // Normalize incoming assignees
    if (!Array.isArray(assignees)) assignees = assignees ? [assignees] : [];
    assignees = assignees.map(String).filter(Boolean);

    // Validate objectId shape
    if (assignees.length > 0 && !isArrayOfObjectIds(assignees)) {
      return res.status(400).json({ message: 'assignees must be array of valid user IDs' });
    }

    // OPTIONAL: ensure users exist
    if (assignees.length > 0) {
      const found = await User.find({ _id: { $in: assignees } }).select('_id').lean();
      const foundIds = new Set(found.map(f => String(f._id)));
      const missing = assignees.filter(id => !foundIds.has(String(id)));
      if (missing.length > 0) {
        return res.status(400).json({ message: 'Some assignees not found', missing });
      }
    }

    // Normalize & derive
    const normalizedStatus = normalizeStatus(status) || 'To Do';

    if (todoChecklist && !Array.isArray(todoChecklist)) todoChecklist = [];
    todoChecklist = todoChecklist.map(x => {
      const obj = typeof x === 'object' && x !== null ? x : { text: String(x || ''), completed: false };
      return { text: String(obj.text || ''), completed: !!obj.completed };
    }).filter(Boolean);

    if (!Array.isArray(subtasks)) subtasks = [];
    subtasks = subtasks.map(s => {
      const o = typeof s === 'object' && s !== null ? s : { title: String(s || ''), isDone: false };
      return { title: String(o.title || ''), isDone: !!o.isDone, assignees: Array.isArray(o.assignees) ? o.assignees : [] };
    });

    const taskData = {
      title,
      description,
      priority,
      project,
      dueDate,
      assignees,
      attachments: Array.isArray(attachments) ? attachments : [],
      subtasks,
      dependencies: Array.isArray(dependencies) ? dependencies : [],
      todoChecklist,
      status: normalizedStatus,
      progress: subtasks.length ? Math.round((subtasks.filter(s => !!s.isDone).length / subtasks.length) * 100) : 0,
      checklistCount: todoChecklist.length
    };

    const task = await Task.create(taskData);

    // 📣 Notify: WhatsApp + Email (fire-and-log)
    console.log(`[createTask] Task created with ID: ${task._id}, initiating notifications...`);
    notifyTaskCreate(task._id).catch(e => console.error('[createTask] notifyTaskCreate error:', e && e.message ? e.message : e));
    notifyTaskCreateEmail(task._id).catch(e => console.error('[createTask] notifyTaskCreateEmail error:', e && e.message ? e.message : e));

    const populated = await populateAssignees(Task.findById(task._id)).lean();
    const enriched = enrichTaskDoc(populated);
    return res.status(201).json({ message: 'Task created', task: enriched });
  } catch (err) {
    console.error('[createTask] error:', err);
    return res.status(500).json({ message: 'Server error', error: err && err.message ? err.message : String(err) });
  }
};

const updateTask = async (req, res) => {
  try {
    if (!mongoose.Types.ObjectId.isValid(String(req.params.id))) return res.status(400).json({ message: 'Invalid task id' });
    const task = await Task.findById(req.params.id);
    if (!task) return res.status(404).json({ message: 'Task not found' });

    // capture old assignees for email diff
    const __oldAssigneesForEmail = Array.isArray(task.assignees) ? task.assignees.map(a => String(a)) : [];

    const fields = ['title','description','priority','project','dueDate','attachments'];
    fields.forEach(f => { if (req.body[f] !== undefined) task[f] = req.body[f]; });

    // handle assignees
    if (req.body.assignees !== undefined) {
      if (!isArrayOfObjectIds(req.body.assignees)) return res.status(400).json({ message: 'assignees must be array of user IDs' });
      task.assignees = req.body.assignees;
    }

    // handle todoChecklist (new)
    if (req.body.todoChecklist !== undefined) {
      if (!Array.isArray(req.body.todoChecklist)) return res.status(400).json({ message: 'todoChecklist must be an array' });
      task.todoChecklist = req.body.todoChecklist.map(i => {
        const obj = typeof i === 'object' && i !== null ? i : { text: String(i || ''), completed: false };
        return { text: String(obj.text || ''), completed: !!obj.completed };
      }).filter(Boolean);
      task.checklistCount = task.todoChecklist.length;

      // derive status from todoChecklist
      task.status = deriveStatusFromTask(task);
    }

    // handle subtasks (legacy)
    if (req.body.subtasks !== undefined) {
      const subs = Array.isArray(req.body.subtasks) ? req.body.subtasks : [];
      task.subtasks = subs.map(s => {
        const o = typeof s === 'object' && s !== null ? s : { title: String(s || ''), isDone: false };
        return { title: String(o.title || ''), isDone: !!o.isDone, assignees: Array.isArray(o.assignees) ? o.assignees : [] };
      });
      // recompute progress
      const doneCount = task.subtasks.filter(x => !!x.isDone).length;
      task.progress = task.subtasks.length ? Math.round((doneCount / task.subtasks.length) * 100) : (typeof task.progress === 'number' ? task.progress : 0);
      // derive status again
      task.status = deriveStatusFromTask(task);
    }

    // handle status direct update (optional)
    if (req.body.status !== undefined) {
      const normalized = normalizeStatus(req.body.status);
      if (!normalized) return res.status(400).json({ message: `Invalid status: ${req.body.status}` });
      task.status = normalized;
      if (normalized === 'Done') {
        (task.subtasks || []).forEach(s => s.isDone = true);
        task.progress = 100;
      }
    }

    // handle dependencies
    if (req.body.dependencies !== undefined) {
      if (!isArrayOfObjectIds(req.body.dependencies)) return res.status(400).json({ message: 'dependencies must be array of task IDs' });
      task.dependencies = req.body.dependencies;
    }

    await task.save();

    // ✉️ Email: notify only newly added assignees
    try {
      const _new = Array.isArray(task.assignees) ? task.assignees.map(a => String(a)) : [];
      const justAdded = _new.filter(id => !__oldAssigneesForEmail.includes(String(id)));
      if (justAdded.length) await notifyNewAssigneesEmail(task._id, justAdded);
    } catch(e) { console.error('notifyNewAssigneesEmail error:', e && e.message ? e.message : e); }

    const populated = await populateAssignees(Task.findById(task._id)).lean();
    const enriched = enrichTaskDoc(populated);
    return res.json({ message: 'Task updated', task: enriched });
  } catch (err) {
    console.error('updateTask error:', err);
    return res.status(500).json({ message: 'Server error', error: err && err.message ? err.message : String(err) });
  }
};

