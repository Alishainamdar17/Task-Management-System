/**
 * Nicely formatted WhatsApp notifications to all assignees for a newly created task.
 */
async function notifyTaskCreate(taskId) {
  try {
    const t = await Task.findById(taskId)
      .populate('assignees', 'name phone')
      .populate('project', 'title')
      .lean();

    if (!t) {
      console.warn(`[notifyTaskCreate] Task ${taskId} not found`);
      return;
    }

    const projectTitle = t.project?.title || 'General';

    const dueStr = t.dueDate
      ? new Date(t.dueDate).toLocaleString('en-GB', {
          timeZone: 'Asia/Kolkata',
          day: '2-digit',
          month: 'short',
          year: '2-digit',
          hour: '2-digit',
          minute: '2-digit',
          hour12: true
        }).replace(',', '')
      : 'N/A';

    // 🔗 App URL (env se, warna fallback)
    const defaultAppUrl = 'https://task-wine-gamma.vercel.app/';
    const appUrl = (process.env.APP_PUBLIC_URL || process.env.CLIENT_URL || defaultAppUrl).trim();

    console.log(
      `[notifyTaskCreate] Task created: ${t.title}, Assignees: ${t.assignees?.length || 0}`
    );

    for (const u of (t.assignees || [])) {
      if (!u?.phone) {
        console.warn(
          `[notifyTaskCreate] Assignee ${u?.name || 'Unknown'} (${u?._id}) has no phone number`
        );
        continue;
      }

      // 🧾 EXACT WhatsApp formatting (bold/italic jaise screenshot me)
      const lines = [
        `👋 *Dear ${u.name || 'User'},*`,
        ``,
        `You have been *assigned a new task.*`,
        ``,
        `*Category* - ${projectTitle}`,
        `*Task* - ${t.title}`,
        `*Priority* - ${t.priority || 'Medium'}`,
        `*Due Date* - ${dueStr}`,
        ``,
        appUrl ? `🔗 *Open App* - ${appUrl}` : null,
        ``,
        `_This is an automated notification generated by your Task Manager._`,
        `Please do not reply`
      ].filter(Boolean);

      const body = lines.join('\n');

      console.log(`[notifyTaskCreate] Sending WhatsApp to ${u.phone} (${u.name})`);
      try {
        await sendText(u.phone, body);
        console.log(`[notifyTaskCreate] ✅ sent to ${u.phone}`);
      } catch (e) {
        console.error(
          `[notifyTaskCreate] ❌ failed ${u.phone}:`,
          e && e.message ? e.message : e
        );
      }
    }
  } catch (err) {
    console.error(
      '[notifyTaskCreate] Error:',
      err && err.message ? err.message : err
    );
  }
}

