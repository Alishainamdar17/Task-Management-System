const getTasks = async (req, res) => {
  try {
    const wantOnlyAssigned = String(req.query.onlyAssigned || '').toLowerCase() === 'true';
    const projectId = req.query.project;
    const isAdmin = isAdminUser(req.user);

    const filter = {};

    if (projectId && mongoose.Types.ObjectId.isValid(String(projectId))) {
      filter.project = projectId;
      // If user asked for onlyAssigned and is NOT admin, filter by assignee
      if (wantOnlyAssigned && !isAdmin) filter.assignees = req.user._id;
      // If user is admin and didn't request onlyAssigned, do not filter by assignees.
    } else {
      // No project specified: default behavior is non-admins see only their tasks
      if (!isAdmin) {
        filter.assignees = req.user._id;
      } else {
        // admin: only apply assignee filter if explicitly requested
        if (wantOnlyAssigned) filter.assignees = req.user._id;
      }
    }

    let q = Task.find(filter).lean();
    q = populateAssignees(q);
    const tasks = await q;
    const tasksWithCounts = tasks.map(enrichTaskDoc);
    return res.json({ tasks: tasksWithCounts });
  } catch (err) {
    console.error('getTasks error:', err);
    return res.status(500).json({ message: 'Server error', error: err && err.message ? err.message : String(err) });
  }
};

