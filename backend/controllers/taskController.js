const getDashboardData = async (req, res) => {
  try {
    const tasks = await Task.find({}).lean();
    const totalTasks = tasks.length;
    const doneTasks = tasks.filter(t => deriveStatusFromTask(t) === 'Done').length;
    const inProgressTasks = tasks.filter(t => deriveStatusFromTask(t) === 'In Progress').length;
    const todoTasks = totalTasks - doneTasks - inProgressTasks;

    const priorities = { Low: 0, Medium: 0, High: 0, Critical: 0 };
    tasks.forEach(t => {
      const p = t.priority || 'Low';
      priorities[p] = (priorities[p] || 0) + 1;
    });

    return res.json({
      totals: { totalTasks, todoTasks, inProgressTasks, doneTasks },
      taskPriorityLevels: priorities
    });
  } catch (err) {
    console.error('getDashboardData error:', err);
    return res.status(500).json({ message: 'Server error', error: err && err.message ? err.message : String(err) });
  }
};

const getUserDashboardData = async (req, res) => {
  try {
    const uid = req.user?._id;
    const tasks = await Task.find({ assignees: uid }).lean();

    const overdueTasks = tasks.filter(t => t.dueDate && new Date(t.dueDate) < new Date() && deriveStatusFromTask(t) !== 'Done').length;

    const priorities = { Low: 0, Medium: 0, High: 0, Critical: 0 };
    tasks.forEach(t => {
      const p = t.priority || 'Low';
      priorities[p] = (priorities[p] || 0) + 1;
    });

    return res.json({
      inProgressTasks: tasks.filter(t => deriveStatusFromTask(t) === 'In Progress').length,
      completedTasks: tasks.filter(t => deriveStatusFromTask(t) === 'Done').length,
      overdueTasks,
      charts: { taskPriorityLevels: priorities }
    });
  } catch (err) {
    console.error('getUserDashboardData error:', err);
    return res.status(500).json({ message: 'Server error', error: err && err.message ? err.message : String(err) });
  }
};

