/* Helpers */
const STATUS_MAP = {
  'todo': 'To Do','to do': 'To Do','to-do': 'To Do',
  'inprogress': 'In Progress','in-progress': 'In Progress','in progress': 'In Progress',
  'done':'Done','completed':'Done','complete':'Done'
};
const normalizeStatus = (raw) => {
  if (raw === undefined || raw === null) return null;
  const key = String(raw).trim().toLowerCase();
  return STATUS_MAP[key] || null;
};

function isArrayOfObjectIds(arr) {
  return Array.isArray(arr) && arr.every(id => mongoose.Types.ObjectId.isValid(String(id)));
}

const populateAssignees = (query) => query.populate('assignees', 'name email phone profileImageUrl');
const enrichTaskDoc = (t) => {
  // ensure plain object
  const task = { ...t };

  const subtasks = Array.isArray(task.subtasks) ? task.subtasks : [];
  const completedSubtaskCount = subtasks.filter(st => !!st.isDone).length;
  const totalSubtasks = subtasks.length;
  task.CompletedSubtaskCount = completedSubtaskCount;

  const todoChecklist = Array.isArray(task.todoChecklist) ? task.todoChecklist : [];
  task.todoChecklist = todoChecklist;
  task.checklistCount = todoChecklist.length;

  task.progress = totalSubtasks > 0
    ? Math.round((completedSubtaskCount / totalSubtasks) * 100)
    : (typeof task.progress === 'number' ? task.progress : 0);

  task.assignees = Array.isArray(task.assignees) ? task.assignees : [];

  return task;
};

/* Derive status from todoChecklist if present; else subtasks; else fallback */
const deriveStatusFromTask = (task) => {
  const todo = Array.isArray(task.todoChecklist) ? task.todoChecklist : null;
  if (todo && todo.length > 0) {
    const doneCount = todo.filter(i => !!i.completed).length;
    if (doneCount === todo.length) return 'Done';
    if (doneCount > 0) return 'In Progress';
    return 'To Do';
  }
  const subs = Array.isArray(task.subtasks) ? task.subtasks : [];
  if (subs.length > 0) {
    const doneCount = subs.filter(s => !!s.isDone).length;
    if (doneCount === subs.length) return 'Done';
    if (doneCount > 0) return 'In Progress';
    return 'To Do';
  }
  return task.status || 'To Do';
};

